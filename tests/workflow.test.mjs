import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';

test('organiser can agree, issue, export, cancel, reassign and invalidate changed tasks',async()=>{
  const dom=new JSDOM(await readFile('index.html','utf8'),{url:'http://localhost/',pretendToBeVisual:true});
  for(const key of ['window','document','localStorage','location','FormData'])globalThis[key]=dom.window[key];
  globalThis.fetch=async url=>({ok:true,json:async()=>JSON.parse(await readFile('.'+url,'utf8'))});
  let printed=0,downloaded;
  dom.window.print=()=>{printed++;assert(document.body.classList.contains('printing-card'));};
  URL.createObjectURL=blob=>{downloaded=blob;return 'blob:synthetic-demo';};URL.revokeObjectURL=()=>{};
  dom.window.HTMLAnchorElement.prototype.click=function(){};
  await import('../src/app.mjs');
  const q=s=>document.querySelector(s);
  const click=s=>{assert(q(s),`Missing ${s}`);q(s).click();};
  const route=async hash=>{location.hash=hash;window.dispatchEvent(new window.Event('hashchange'));await new Promise(r=>setTimeout(r,10));};
  assert.equal(document.querySelectorAll('.meeting').length,6);
  assert(q('#issue').disabled);
  click('#talent-yes');assert(q('#issue').disabled);assert(q('#talent-yes').disabled);
  click('#company-yes');assert(!q('#issue').disabled);
  click('#issue');assert(q('.intro-card'));assert(q('#issue').disabled);
  click('#print');assert.equal(printed,1);assert(!document.body.classList.contains('printing-card'));
  click('#calendar');const calendar=await downloaded.text();assert.match(calendar,/DTSTART:20261119T120000Z/);assert.match(calendar,/SYNTHETIC Talent 01/);
  click('#checkin');assert(q('#checkin').disabled);assert.match(q('.match-detail').textContent,/Introduced/);
  click('#export');assert.match(await downloaded.text(),/SYNTHETIC DEMO/);assert.match(await downloaded.text(),/card ready/);
  // Give one other pair mutual agreement; cancelling the first cannot move it.
  click('[data-meeting="p2:c2:14:00"]');click('#talent-yes');click('#company-yes');
  click('[data-meeting="p1:c1:14:00"]');click('#cancel');
  assert.equal(document.querySelectorAll('.meeting').length,5);assert(!q('[data-meeting="p1:c1:14:00"]'));
  click('#replan');assert.equal(document.querySelectorAll('.meeting').length,6);
  const saved=JSON.parse(localStorage.getItem('common-ground-v1'));
  assert(saved.state.meetings.some(m=>m.personId==='p7'));
  assert(saved.state.meetings.some(m=>m.personId==='p2'&&m.companyId==='c2'&&m.slot==='14:00'));
  const newMeeting=saved.state.meetings.find(m=>m.personId==='p7');
  click(`[data-meeting="${newMeeting.personId}:${newMeeting.companyId}:${newMeeting.slot}"]`);
  assert(!q('#talent-yes').disabled);assert(!q('#company-yes').disabled);assert(q('#issue').disabled);assert(!q('.intro-card'));
  await route('#audit');assert.match(q('#audit-summary').textContent,/16\/16/);
  click('#baseline-toggle');assert(q('.baseline-comparison'));
  for(const a of document.querySelectorAll('.proof-links a'))await readFile('.'+a.getAttribute('href'));
  await route('#evidence');click('[data-person="p7"]');
  assert(JSON.parse(localStorage.getItem('common-ground-v1')).state.unavailable.includes('p7'));
  await route('#needs');
  q('#task-c1').value='<img src=x onerror=alert(1)> A different task';
  q('[data-company="c1"]').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  assert.equal(q('#task-c1').value,'<img src=x onerror=alert(1)> A different task');
  assert(!q('img'));const after=JSON.parse(localStorage.getItem('common-ground-v1'));
  assert.equal(after.data.companies[0].needs.length,0);assert.equal(Object.keys(after.state.approvals).length,0);assert.equal(after.state.issued.length,0);
  click('#reset');await route('#desk');assert.equal(document.querySelectorAll('.meeting').length,6);assert(q('#issue').disabled);
  dom.window.close();
});
